/**
 * Client-Side Gemini AI Service (BYOK: Bring Your Own Key)
 * Allows users to provide their own free Gemini API key to run AI summaries
 * directly from their browser on static hosts like GitHub Pages.
 * Ensures the app owner's personal credits are never consumed by third-party visitors.
 */

const GEMINI_KEY_STORAGE = "vornal_user_gemini_api_key";

export function getUserGeminiApiKey(): string {
  try {
    return localStorage.getItem(GEMINI_KEY_STORAGE) || "";
  } catch {
    return "";
  }
}

export function setUserGeminiApiKey(key: string): void {
  try {
    const trimmed = key.trim();
    if (trimmed) {
      localStorage.setItem(GEMINI_KEY_STORAGE, trimmed);
    } else {
      localStorage.removeItem(GEMINI_KEY_STORAGE);
    }
  } catch {}
}

export interface ClientTranscribeResult {
  title: string;
  mood: string;
  keyThemes: string[];
  summary: string;
  actionItems: string[];
  transcript: string;
  markdown: string;
}

export async function transcribeWithClientGeminiKey(
  apiKey: string,
  audioBase64: string,
  mimeType: string,
  dateString: string,
  audioFileName: string,
  userTags: string[]
): Promise<ClientTranscribeResult> {
  const cleanMime = mimeType.split(";")[0] || "audio/webm";

  const systemInstruction = `You are Vornal, an intelligent, empathetic, and structured voice journal companion.
Analyze the user's spoken audio journal entry and synthesize it into a structured JSON response.

Return a valid JSON object matching this structure:
{
  "title": "A concise, poetic, or evocative title (3 to 6 words)",
  "mood": "Single mood/tone descriptor (e.g., Reflective, Calm, Energized, Frustrated, Grateful, Focused, Melancholic)",
  "keyThemes": ["theme1", "theme2", "theme3"],
  "summary": "2-3 concise sentences capturing the core essence, emotion, and thoughts expressed.",
  "actionItems": ["Actionable reflection 1", "Actionable reflection 2"],
  "transcript": "Verbatim transcript of everything spoken."
}`;

  const prompt = `Date: ${dateString}
User Tags: ${userTags.join(", ") || "None"}
Please transcribe and synthesize the attached voice journal recording into the requested JSON schema.`;

  // Gemini 2.5 Flash endpoint
  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${encodeURIComponent(
    apiKey.trim()
  )}`;

  const body = {
    contents: [
      {
        parts: [
          {
            inline_data: {
              mime_type: cleanMime,
              data: audioBase64,
            },
          },
          {
            text: prompt,
          },
        ],
      },
    ],
    systemInstruction: {
      parts: [{ text: systemInstruction }],
    },
    generationConfig: {
      responseMimeType: "application/json",
      temperature: 0.3,
    },
  };

  const response = await fetch(url, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify(body),
  });

  if (!response.ok) {
    const errData = await response.json().catch(() => ({}));
    throw new Error(
      errData.error?.message || `Gemini API responded with error code ${response.status}`
    );
  }

  const json = await response.json();
  const rawText = json.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!rawText) {
    throw new Error("No response content generated by Gemini API.");
  }

  const parsed = JSON.parse(rawText);

  // Rebuild Markdown format
  const dateFormatted = new Date(dateString).toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });

  const tagsFormatted = (userTags || []).map((t) => `#${t}`).join(" ");
  const themesList = (parsed.keyThemes || []).map((t: string) => `- ${t}`).join("\n");
  const actionsList = (parsed.actionItems || []).map((a: string) => `- [ ] ${a}`).join("\n");

  const markdown = `# ${parsed.title || "Voice Journal"}

**Date:** ${dateFormatted}
**Mood / Tone:** ${parsed.mood || "Reflective"}
**Audio File:** \`${audioFileName}\`
**Tags:** ${tagsFormatted || "#journal"}

---

## Executive Summary
${parsed.summary || "Voice reflection recorded with Vornal."}

## Key Themes
${themesList || "- Personal reflection"}

## Action Items & Insights
${actionsList || "- [ ] Reflect on today's session"}

## Transcript
${parsed.transcript || "Spoken recording captured."}
`;

  return {
    title: parsed.title || "Voice Journal",
    mood: parsed.mood || "Reflective",
    keyThemes: parsed.keyThemes || [],
    summary: parsed.summary || "",
    actionItems: parsed.actionItems || [],
    transcript: parsed.transcript || "",
    markdown,
  };
}
